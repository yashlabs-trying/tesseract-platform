from __future__ import annotations
from datetime import datetime
from decimal import Decimal
from typing import Dict, List, Optional, Any
from fusion.models.types import (
    FusionRecommendation, DeploymentAlternative, ExpectedOutcome,
    RecommendationStatus, GPUInventory, ModelDeployment, TenantPolicy,
)


class RecommendationReport:
    def __init__(self, recommendation: FusionRecommendation):
        self._rec = recommendation
        self._generated_at = datetime.utcnow()

    def to_markdown(self) -> str:
        lines = []
        lines.append("# Tesseract Fusion — Optimization Recommendation")
        lines.append("")
        lines.append(f"**Recommendation ID:** {self._rec.recommendation_id}")
        lines.append(f"**Generated:** {self._generated_at.isoformat()}")
        lines.append(f"**Status:** {self._rec.approval_status.value}")
        lines.append(f"**Confidence:** {self._rec.confidence:.1%}")
        lines.append(f"**Engine:** {self._rec.provenance.get('engine', 'unknown')}")
        lines.append("")
        lines.append("## Economics Summary")
        lines.append("")
        lines.append("| Metric | Baseline | Recommended | Delta |")
        lines.append("|--------|----------|-------------|-------|")
        lines.append(self._format_econ_row(
            "Revenue",
            self._rec.baseline_economics.expected_revenue,
            self._rec.expected_economics.expected_revenue,
        ))
        lines.append(self._format_econ_row(
            "Operating Cost",
            self._rec.baseline_economics.expected_operating_cost,
            self._rec.expected_economics.expected_operating_cost,
        ))
        lines.append(self._format_econ_row(
            "Contribution Margin",
            self._rec.baseline_economics.expected_contribution_margin or Decimal("0"),
            self._rec.expected_economics.expected_contribution_margin or Decimal("0"),
        ))
        lines.append("")
        lines.append("## Baseline Plan")
        lines.append("")
        for alt in self._rec.baseline_plan:
            lines.append(f"- **{alt.deployment_id}**: {alt.replica_count} replicas on {alt.gpu_type}")
            lines.append(f"  - Cost: ${alt.estimated_cost_per_hour}/hr")
            rev = alt.estimated_revenue_per_hour
            if rev is not None:
                lines.append(f"  - Revenue: ${rev}/hr")
        lines.append("")
        lines.append("## Recommended Plan")
        lines.append("")
        for alt in self._rec.recommended_plan:
            lines.append(f"- **{alt.deployment_id}**: {alt.replica_count} replicas on {alt.gpu_type}")
            lines.append(f"  - Pool: {alt.gpu_pool_id}")
            lines.append(f"  - Cost: ${alt.estimated_cost_per_hour}/hr")
            lines.append(f"  - Policy: {alt.warm_policy}")
            if alt.cold_start_risk:
                lines.append(f"  - Risk: {alt.cold_start_risk}")
        lines.append("")
        if self._rec.rejected_alternatives:
            lines.append("## Rejected Alternatives")
            lines.append("")
            for alt, reason in self._rec.rejected_reasons.items():
                lines.append(f"- **{alt}**: {reason}")
            lines.append("")
        if self._rec.risk_explanation:
            lines.append("## Risk Assessment")
            lines.append("")
            lines.append(self._rec.risk_explanation)
            lines.append("")
        if self._rec.alternative_plans:
            lines.append("## Alternative Plans Considered")
            lines.append("")
            for i, alt_list in enumerate(self._rec.alternative_plans):
                if alt_list:
                    names = ", ".join(f"{a.deployment_id} ({a.replica_count}x {a.gpu_type})" for a in alt_list[:3])
                    lines.append(f"- Option {i + 1}: {names}")
            lines.append("")
        lines.append("## Action Required")
        lines.append("")
        lines.append(f"This recommendation is **{self._rec.approval_status.value}**.")
        if self._rec.execution_eligibility:
            lines.append("This recommendation is eligible for automated execution pending approval.")
        else:
            lines.append("Automated execution is not available. An operator must review and approve.")
        lines.append("")
        lines.append("---")
        lines.append("*This report was generated by Tesseract Fusion v0.2.0 in advisory mode.*")
        return "\n".join(lines)

    def _format_econ_row(self, label: str, baseline: Decimal, recommended: Decimal) -> str:
        delta = recommended - baseline
        delta_str = f"+${delta}" if delta > 0 else f"${delta}"
        return f"| {label} | ${baseline} | ${recommended} | {delta_str} |"


class ReportGenerator:
    def generate(self, recommendation: FusionRecommendation) -> RecommendationReport:
        return RecommendationReport(recommendation)

    def generate_markdown(self, recommendation: FusionRecommendation) -> str:
        return self.generate(recommendation).to_markdown()

    def compare_baseline_candidate(
        self,
        baseline: FusionRecommendation,
        candidate: FusionRecommendation,
    ) -> str:
        lines = []
        lines.append("# Tesseract Fusion — Baseline vs Candidate Comparison")
        lines.append("")
        lines.append(f"**Baseline ID:** {baseline.recommendation_id}")
        lines.append(f"**Candidate ID:** {candidate.recommendation_id}")
        lines.append("")
        lines.append("## Economic Comparison")
        lines.append("")
        lines.append("| Metric | Baseline | Candidate | Delta |")
        lines.append("|--------|----------|-----------|-------|")
        lines.append(self._format_compare_row(
            "Revenue",
            baseline.expected_economics.expected_revenue,
            candidate.expected_economics.expected_revenue,
        ))
        lines.append(self._format_compare_row(
            "Cost",
            baseline.expected_economics.expected_operating_cost,
            candidate.expected_economics.expected_operating_cost,
        ))
        lines.append(self._format_compare_row(
            "Contribution",
            baseline.expected_economics.expected_contribution_margin or Decimal("0"),
            candidate.expected_economics.expected_contribution_margin or Decimal("0"),
        ))
        lines.append("")
        lines.append("## Deployment Changes")
        lines.append("")
        baseline_map = {a.deployment_id: a for a in baseline.recommended_plan}
        for alt in candidate.recommended_plan:
            current = baseline_map.get(alt.deployment_id)
            if current and (current.gpu_type != alt.gpu_type or current.replica_count != alt.replica_count):
                lines.append(f"- **{alt.deployment_id}**: {current.replica_count}x {current.gpu_type} → {alt.replica_count}x {alt.gpu_type}")
            elif current is None:
                lines.append(f"- **{alt.deployment_id}**: NEW — {alt.replica_count}x {alt.gpu_type}")
        lines.append("")
        lines.append("---")
        return "\n".join(lines)

    def _format_compare_row(self, label: str, b: Decimal, c: Decimal) -> str:
        delta = c - b
        ds = f"+${delta}" if delta > 0 else f"${delta}"
        return f"| {label} | ${b} | ${c} | {ds} |"
